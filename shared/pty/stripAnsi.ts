//
// **버퍼는 원본을 들고 있다** (`outputBuffer.ts` 가 일부러 안 벗긴다) — 벗기는 것은
// 읽는 층의 일이라, 화면은 색을 그대로 그리고 모델·판정만 벗은 글자를 본다.
//
// 사본이 둘이었다 (`electron/mcp/readLogs.ts` · `src/state/runHeal.ts`). 한쪽 주석은
// **"합치지 않는다 — 공유하려면 `shared/` 로 옮겨야 하는데 그 이사는 이 두 줄이 값을
// 못 한다"** 였고, 그때는 맞는 말이었다. 지금 옮기는 이유는 사본이 늘어서가 아니라
// **이사 값이 내려가서다** — `shared/errors/describeError` 를 놓으면서 main·렌더러가
// 함께 쓰는 한 줄짜리를 `shared/` 에 두는 길이 이미 났다 (2026-08-17).
//
// 판정과 화면이 **같은 글자를 봐야 한다**는 것도 이제 근거가 된다: `runHeal` 이 로그에서
// 실패를 알아보고, `readLogs` 가 그 로그를 모델에게 넘긴다. 두 벌이 갈리면 한쪽만 걸린다.

/**
 * CSI(색·커서)와 OSC(창 제목) 둘만 벗긴다 — 터미널 출력에서 실제로 오는 것이 이 둘이다.
 *
 * 전부를 훑지 않는 이유: 안 오는 것까지 지우려 들면 정규식이 길어지는 만큼 **멀쩡한
 * 본문을 먹을 위험**이 는다. 실제로 오는 것이 늘면 그때 실측으로 더한다.
 */
export function stripAnsi(text: string): string {
  return text
    .replace(/\u001b\[[0-9;?]*[ -/]*[@-~]/g, '')
    .replace(/\u001b\][^\u0007\u001b]*(?:\u0007|\u001b\\)/g, '')
}
