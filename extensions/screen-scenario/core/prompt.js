// 에이전트에게 보낼 말.
//
// **이 질문은 사용자 대화의 턴이 된다** (`code.chat.ask`, 설계 §3.1). 질문도 답도 화면에
// 그대로 보이므로, 사람이 읽어도 말이 되게 쓴다 — 기계용 지시문처럼 쓰면 대화에 흉하게
// 남고, 사용자가 이어서 "결재 화면도 넣어줘" 라고 말하기 어려워진다.
//
// **규칙으로 훑지 않는 이유**를 프롬프트가 알고 있어야 한다. 예전 판이 실측으로 남긴 것:
// 라우터 접두사가 파일 셋에 걸쳐 별칭으로 이어지고, `pages/` 밑에 화면과 부품이 섞이고,
// 규칙이 만든 문장은 "저장 정상" 을 못 넘는다. 셋 다 **코드를 읽어야** 풀린다.

/** 답의 모양. 프롬프트에 그대로 실어 보낸다. */
const SHAPE = `{
  "screens": [
    { "name": "주문 목록 조회", "file": "src/pages/order/OrderList.tsx" }
  ]
}`

/**
 * 처음 훑을 때.
 *
 * `name` 은 **사람이 부르는 이름**이다. 파일 이름을 그대로 옮겨 적으면 목록이 두 줄인
 * 뜻이 없어진다 (위는 이름, 아래는 파일).
 */
function findPrompt() {
  return `이 프로젝트에서 **사용자가 실제로 보는 화면**을 찾아 주세요.

- 화면 하나 = 파일 하나로 잡습니다. 부품(버튼·표 같은 조각)은 빼 주세요.
- \`name\` 은 사람이 부르는 이름입니다 (예: "주문 목록 조회"). 파일 이름을 그대로 옮기지 마세요.
- \`file\` 은 프로젝트 루트 기준 상대경로입니다.
- 확실하지 않으면 넣지 마세요. 빠뜨린 것은 나중에 사람이 직접 넣습니다.

답은 **JSON 한 덩이**로만 주세요. 설명은 붙이지 않아도 됩니다.

${SHAPE}`
}

/**
 * 다시 훑을 때. **있는 목록을 먼저 준다.**
 *
 * 그냥 다시 물으면 답이 매번 흔들려 목록이 늘었다 줄었다 한다. 지금 것을 보여 주고
 * ①없어졌는지 확인 ②새로 생긴 것 찾기 순으로 시키면 흔들림이 줄어든다.
 * (그래도 못 믿는 몫은 `merge.js` 의 20% 방어가 받는다.)
 */
function refindPrompt(screens) {
  const known = screens.map((one) => `- ${one.name} (${one.id})`).join('\n')

  return `이 프로젝트의 화면 목록을 갱신해 주세요. 지금 알고 있는 것은 이렇습니다:

${known}

두 가지를 봐 주세요.
1. 위 목록 중 **코드에서 사라진 것**이 있는지 (파일이 없어졌거나 더 이상 화면이 아닌 것)
2. 목록에 **없는 새 화면**이 있는지

살아 있는 것과 새로 찾은 것을 **함께** 담아 주세요 — 답에 없는 것은 사라진 것으로 봅니다.
확실하지 않으면 그대로 두세요.

답은 **JSON 한 덩이**로만 주세요.

${SHAPE}`
}

module.exports = { findPrompt, refindPrompt, SHAPE }
